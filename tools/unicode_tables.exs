# Writes BeamMCP.Signer.COSE.Unicode, the N6 text rule's four tables, from the Unicode 15.0.0
# data files in <dir> (tools/unicode_tables.sh fetches and pins them):
#
#   elixir tools/unicode_tables.exs <dir> <out.ex>
#
# Cn and Cf from DerivedGeneralCategory.txt; ccc from DerivedCombiningClass.txt (UnicodeData.txt's
# field 3, extracted); NFC_QC No and Maybe from DerivedNormalizationProps.txt. Each table is a
# tuple of ranges sorted by first code point, adjacent ranges of one value merged, so a lookup is
# a binary search over a literal. Prints each table's code-point count, for the profile's figures
# (Cf 170, NFC_QC=No 1,120, NFC_QC=Maybe 111).
[dir, out] = System.argv()

read = fn file, keep ->
  Path.join(dir, file)
  |> File.stream!()
  |> Stream.map(&(&1 |> String.split("#") |> hd() |> String.trim()))
  |> Stream.reject(&(&1 == ""))
  |> Stream.map(fn line ->
    [range | fields] = line |> String.split(";") |> Enum.map(&String.trim/1)

    {lo, hi} =
      case String.split(range, "..") do
        [one] -> {String.to_integer(one, 16), String.to_integer(one, 16)}
        [lo, hi] -> {String.to_integer(lo, 16), String.to_integer(hi, 16)}
      end

    {lo, hi, fields}
  end)
  |> Enum.flat_map(fn {lo, hi, fields} ->
    case keep.(fields) do
      nil -> []
      value -> [{lo, hi, value}]
    end
  end)
  |> Enum.sort()
  |> Enum.reduce([], fn
    {lo, hi, v}, [{plo, phi, v} | rest] when lo == phi + 1 -> [{plo, hi, v} | rest]
    range, acc -> [range | acc]
  end)
  |> Enum.reverse()
end

gc = fn cat -> fn [c] -> if c == cat, do: true end end
qc = fn value -> fn fields -> if fields == ["NFC_QC", value], do: true end end

tables = [
  unassigned: read.("DerivedGeneralCategory.txt", gc.("Cn")),
  format: read.("DerivedGeneralCategory.txt", gc.("Cf")),
  nfc_no: read.("DerivedNormalizationProps.txt", qc.("N")),
  nfc_maybe: read.("DerivedNormalizationProps.txt", qc.("M"))
]

ccc =
  read.("DerivedCombiningClass.txt", fn [c] ->
    case String.to_integer(c) do
      0 -> nil
      n -> n
    end
  end)

count = fn ranges -> Enum.reduce(ranges, 0, fn {lo, hi, _}, n -> n + hi - lo + 1 end) end

for {name, ranges} <- tables ++ [ccc: ccc] do
  IO.puts("#{name}: #{count.(ranges)} code points in #{length(ranges)} ranges")
end

hex = &("0x" <> String.pad_leading(Integer.to_string(&1, 16), 4, "0"))

literal = fn
  ranges, :pairs -> Enum.map_join(ranges, ",\n      ", fn {lo, hi, _} -> "{#{hex.(lo)}, #{hex.(hi)}}" end)
  ranges, :triples -> Enum.map_join(ranges, ",\n      ", fn {lo, hi, c} -> "{#{hex.(lo)}, #{hex.(hi)}, #{c}}" end)
end

functions =
  Enum.map_join(tables, "\n\n", fn {name, ranges} ->
    "  def #{name} do\n    {\n      #{literal.(ranges, :pairs)}\n    }\n  end"
  end)

File.write!(out, """
# SPDX-FileCopyrightText: 2026 Sudo Apt Holdings LLC
# SPDX-FileCopyrightText: 2022 Unicode, Inc.
# SPDX-License-Identifier: Apache-2.0 AND Unicode-3.0

defmodule BeamMCP.Signer.COSE.Unicode do
  @moduledoc false
  # GENERATED by tools/unicode_tables.exs from the Unicode 15.0.0 data files
  # (tools/unicode_tables.sh pins each by sha256); do not edit by hand. The four tables of the
  # N6 text rule (profile v0.1 §2.4) and the canonical combining classes, as ranges sorted by first
  # code point: Cn (unassigned), Cf (format controls), NFC_Quick_Check No and Maybe, and every
  # code point whose ccc is not 0 with its class. The data is Unicode's, under the Unicode
  # License v3; the profile pins this version, so the runtime's own Unicode tables are never read.

  def version, do: "15.0.0"

#{functions}

  def ccc do
    {
      #{literal.(ccc, :triples)}
    }
  end
end
""")
